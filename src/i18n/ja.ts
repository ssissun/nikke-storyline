export function japanese(text: string): string {
  const value = text.trim().replace(/\s+/g, ' ');
  if (ja[value] !== undefined) return ja[value];
  const anniversary = value.match(/^(\d+(?:\.\d+)?)주년$/);
  if (anniversary) return `${anniversary[1]}周年`;
  const newYear = value.match(/^(\d+) 신년$/);
  if (newYear) return `20${newYear[1]}年新年`;
  const more = value.match(/^외 (\d+)건$/);
  if (more) return `ほか${more[1]}件`;
  const meta = value.match(/^최종 갱신 · (.+?) · 본 가이드는 커뮤니티 의견들을 취합하고 개인의 취향을 첨가하여 작성됨$/);
  if (meta) return `最終更新 · ${meta[1]} · コミュニティの意見と個人の好みをもとに作成したガイドです`;
  const thumb = value.match(/^(.*?) 썸네일 크게 보기(?: \((\d+)장\))?$/);
  if (thumb) return `${japanese(thumb[1])}の画像を拡大${thumb[2] ? `（${thumb[2]}枚）` : ''}`;
  const watched = value.match(/^(.*?) 감상 완료$/);
  if (watched) return `${japanese(watched[1])}を既読にする`;
  return text;
}
